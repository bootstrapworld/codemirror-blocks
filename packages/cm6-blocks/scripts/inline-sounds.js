// Writes src/sounds.ts: the two sounds of the old editor (copied unchanged from packages/codemirror-blocks/assets/sounds) as data URLs, so that
// importing the package needs no bundler rule for audio files. They are tiny (about 4.6 KB of base64). Run `node scripts/inline-sounds.js` after
// changing a file in assets/sounds.
const fs = require("fs");
const path = require("path");

const dir = path.join(__dirname, "..", "assets", "sounds");
const url = (name) =>
  "data:audio/mpeg;base64," +
  fs.readFileSync(path.join(dir, name)).toString("base64");

const out = `// Generated by scripts/inline-sounds.js from assets/sounds: do not edit.
export const BEEP_URL =
  "${url("beep.mp3")}";
export const WRAP_URL =
  "${url("wrap.mp3")}";
`;
fs.writeFileSync(path.join(__dirname, "..", "src", "sounds.ts"), out);
