// Writes src/sounds.ts: the two sounds as data URLs, so that importing the
// library needs no bundler rule for audio files. The sounds are tiny; run
// `npm run build-sounds` after changing a file in assets/sounds.
const fs = require("fs");
const path = require("path");

const dir = path.join(__dirname, "..", "assets", "sounds");
const url = (name) =>
  "data:audio/mpeg;base64," +
  fs.readFileSync(path.join(dir, name)).toString("base64");

const out = `// Generated by scripts/inline-sounds.js from assets/sounds: do not edit.
export const BEEP_URL =
  "${url("beep.mp3")}";
export const WRAP_URL =
  "${url("wrap.mp3")}";
`;
fs.writeFileSync(path.join(__dirname, "..", "src", "sounds.ts"), out);
